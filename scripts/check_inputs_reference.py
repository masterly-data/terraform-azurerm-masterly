#!/usr/bin/env python3
"""Generate, and check, docs/inputs.md: every input of the module, grouped by subsystem.

The module's 100-odd inputs live in several files: variables.tf, in sections headed
`# --- <title> ---`, and one file per optional subsystem (keyvault.tf, redis.tf, ...). The
Terraform Registry lists them alphabetically, which is no help in finding what a subsystem
needs. This script writes them as one page, grouped the way the code is:

  variables.tf  inputs before the first section header under "Core", then one group per header
  <file>.tf     one group per file, titled from FILE_TITLES below

Each row gives the input, its type (marked sensitive where it is), its default (or "required"),
and the first sentence of its description. The description stays the source of truth.

  --write      rewrite docs/inputs.md
  (no flag)    fail when docs/inputs.md differs from what --write would produce, or when a
               root .tf file declares inputs and has no title in FILE_TITLES
  --selftest   prove the check can fail

Standard library only, like the other release scripts.
"""

from __future__ import annotations

import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path("docs/inputs.md")

# A root .tf file that declares inputs needs a title here; the check refuses one that has none,
# so a new subsystem cannot land without a place on the page.
FILE_TITLES = {
    "keyvault.tf": "Key Vault",
    "redis.tf": "Redis",
    "workers.tf": "Workers",
    "migrate.tf": "Migrations",
    "entra-auth.tf": "Database and Redis authentication",
    "email.tf": "Email",
    "registry.tf": "Registry private endpoint",
    "diagnostics.tf": "Diagnostics and alerts",
}

SECTION_RE = re.compile(r"^# --- (?P<t>.+?) -{3,}\s*$")
VAR_RE = re.compile(r'^variable "(?P<n>[^"]+)" \{\n(?P<b>.*?)^\}', re.S | re.M)
TYPE_RE = re.compile(r"^  type\s*=\s*(?P<v>.+)$", re.M)
DEFAULT_RE = re.compile(r"^  default\s*=\s*(?P<v>.+)$", re.M)
DESC_LINE_RE = re.compile(r'^  description\s*=\s*"(?P<v>(?:[^"\\]|\\.)*)"\s*$', re.M)
DESC_HEREDOC_RE = re.compile(r"^  description\s*=\s*<<-?(?P<tag>\w+)\n(?P<v>.*?)^\s*(?P=tag)\s*$", re.S | re.M)
SENSITIVE_RE = re.compile(r"^  sensitive\s*=\s*true", re.M)
# The end of the first sentence: a full stop, after a word character or a closing bracket or
# quote, then whitespace. "e.g." and "i.e." are not ends.
SENTENCE_END_RE = re.compile(r"(?<!\be\.g)(?<!\bi\.e)(?<=[\w\)\]`\"'])\.\s")

HEADER = """# Module inputs

<!-- Generated by scripts/check_inputs_reference.py --write from the module's .tf files. Do not
edit: change the variable's description instead, and regenerate. -->

Every input of the module, grouped by the subsystem it configures. Each row gives the first
sentence of the input's description; the full description is in the `.tf` file named in the
group heading, and on the Terraform Registry. **Required** means the input has no default.
Production (`mode = "production"`) refuses a plan until more inputs are set: the plan names
each one that is missing.
"""


def first_sentence(text: str) -> str:
    text = " ".join(text.replace('\\"', '"').split())
    m = SENTENCE_END_RE.search(text)
    s = text[: m.start() + 1] if m else text
    return s if len(s) <= 220 else s[:217].rstrip() + "..."


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def describe(name: str, body: str) -> dict:
    t = TYPE_RE.search(body)
    d = DEFAULT_RE.search(body)
    desc = DESC_LINE_RE.search(body) or DESC_HEREDOC_RE.search(body)
    typ = t.group("v").strip() if t else "any"
    if typ.endswith("({") or typ.endswith("{") or typ.endswith("(["):
        typ = typ.split("(")[0] + "(...)"
    if d is None:
        default = "required"
    else:
        v = d.group("v").strip()
        default = f"`{v}`" if len(v) <= 40 and not v.endswith(("{", "[", "(")) else "see file"
    return {
        "name": name,
        "type": typ + (", sensitive" if SENSITIVE_RE.search(body) else ""),
        "default": default,
        "desc": first_sentence(desc.group("v")) if desc else "",
    }


def collect(root: Path) -> tuple[list[tuple[str, str, list[dict]]], list[str]]:
    groups: list[tuple[str, str, list[dict]]] = []
    problems: list[str] = []
    vt = root / "variables.tf"
    if vt.is_file():
        # Walk variables.tf in order, switching group at each section header.
        title = "Core"
        buf: list[str] = []
        sections: list[tuple[str, str]] = []
        for line in vt.read_text().split("\n"):
            m = SECTION_RE.match(line)
            if m:
                sections.append((title, "\n".join(buf)))
                title, buf = m.group("t").strip(), []
            else:
                buf.append(line)
        sections.append((title, "\n".join(buf)))
        for title, text in sections:
            rows = [describe(m.group("n"), m.group("b")) for m in VAR_RE.finditer(text)]
            if rows:
                groups.append((title, "variables.tf", rows))
    for f in sorted(root.glob("*.tf")):
        if f.name == "variables.tf":
            continue
        rows = [describe(m.group("n"), m.group("b")) for m in VAR_RE.finditer(f.read_text())]
        if not rows:
            continue
        if f.name not in FILE_TITLES:
            problems.append(
                f"{f.name} declares inputs but has no title in FILE_TITLES in "
                f"scripts/check_inputs_reference.py"
            )
            continue
        groups.append((FILE_TITLES[f.name], f.name, rows))
    return groups, problems


def render(groups) -> str:
    total = sum(len(r) for _, _, r in groups)
    out = [HEADER, f"{total} inputs in {len(groups)} groups.\n", "## Groups\n"]
    for title, fname, rows in groups:
        anchor = re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")
        out.append(f"- [{title}](#{anchor}) ({len(rows)})")
    out.append("")
    for title, fname, rows in groups:
        out.append(f"## {title}\n")
        out.append(f"In `{fname}`.\n")
        out.append("| Input | Type | Default | Description |")
        out.append("|---|---|---|---|")
        for r in rows:
            out.append(
                f"| `{r['name']}` | `{cell(r['type'])}` | {cell(r['default'])} | {cell(r['desc'])} |"
            )
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def run(root: Path, write: bool) -> list[str]:
    groups, problems = collect(root)
    if problems:
        return problems
    text = render(groups)
    target = root / OUT
    if write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
        return []
    if not target.is_file() or target.read_text() != text:
        return [f"{OUT} is out of date: run python3 scripts/check_inputs_reference.py --write"]
    return []


def selftest() -> int:
    failures = []
    d = Path(tempfile.mkdtemp())
    (d / "variables.tf").write_text(
        'variable "mode" {\n  type        = string\n  default     = "demo"\n'
        '  description = "The posture. More text follows."\n}\n\n'
        "# --- Identity (ADR 0024) ------------------------------\n\n"
        'variable "oidc_client_id" {\n  type        = string\n'
        '  description = "Client id, e.g. a GUID. Second."\n}\n'
    )
    (d / "redis.tf").write_text(
        'variable "enable_redis" {\n  type        = bool\n  default     = false\n'
        '  sensitive   = true\n  description = <<-EOT\n    Turn it on. Then more.\n  EOT\n}\n'
    )

    def expect(name, problems, ok):
        if (not problems) != ok:
            failures.append(f"{name}: expected {'pass' if ok else 'fail'}, got {problems}")

    expect("missing page", run(d, False), False)
    expect("write", run(d, True), True)
    expect("fresh page", run(d, False), True)
    page = (d / OUT).read_text()
    for want in ("## Core", "## Identity (ADR 0024)", "## Redis", "| `oidc_client_id` | `string` | required | Client id, e.g. a GUID. |",
                 "`bool, sensitive`", "Turn it on."):
        if want not in page:
            failures.append(f"page lacks {want!r}")
    (d / "variables.tf").write_text((d / "variables.tf").read_text().replace("The posture.", "The stance."))
    expect("stale page", run(d, False), False)
    run(d, True)
    (d / "newthing.tf").write_text('variable "x" {\n  type = string\n  description = "X."\n}\n')
    expect("untitled file", run(d, False), False)

    for f in failures:
        print(f"SELFTEST FAIL: {f}")
    print("selftest:", "FAIL" if failures else "OK")
    return 1 if failures else 0


def main() -> int:
    if "--selftest" in sys.argv:
        return selftest()
    problems = run(ROOT, "--write" in sys.argv)
    for p in problems:
        print(p)
    print("OK" if not problems else f"FAIL: {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
